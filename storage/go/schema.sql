CREATE TABLE IF NOT EXISTS document (
 id INTEGER PRIMARY KEY, role TEXT NOT NULL, key TEXT NOT NULL,
 revision INTEGER NOT NULL CHECK(revision>0), UNIQUE(role,key)
);
CREATE TABLE IF NOT EXISTS field (id INTEGER PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS node (
 document_id INTEGER NOT NULL REFERENCES document(id) ON DELETE CASCADE,
 node_id INTEGER NOT NULL, parent_id INTEGER NOT NULL, slot INTEGER NOT NULL,
 kind INTEGER NOT NULL CHECK(kind BETWEEN 0 AND 8), value,
 PRIMARY KEY(document_id,node_id)
) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS migration (
 role TEXT NOT NULL, key TEXT NOT NULL, source TEXT NOT NULL, sha256 TEXT NOT NULL,
 PRIMARY KEY(role,key,source)
) WITHOUT ROWID;
